export function inferSiglasFromName(name: string): string | null {
  const upper = (name || '').toUpperCase().trim()
  for (const [prefix, siglas] of NAME_TO_SIGLAS_FALLBACK) {
    if (upper.startsWith(prefix)) return siglas
  }
  return null
}

const SKIP = new Set(['de', 'del', 'la', 'las', 'los', 'el', 'y', 'e', 'en', 'para', 'por', 'a', 'al', 'con'])
/** No published siglas: the initials of the significant words («Instituto Potosino de Investigación Científica y
 *  Tecnológica, A.C.» → IPICT); legal suffixes dropped. The full name rides in the label and the title. */
export function initialsOf(name: string): string | null {
  const words = name.replace(/,?\s*(S\.?\s*A\.?(\s*de\s*C\.?\s*V\.?)?|A\.?\s*C\.?|S\.?\s*C\.?)\s*$/i, '')
    .split(/[\s,.-]+/).filter((w) => w && !SKIP.has(w.toLowerCase()))
  const out = words.map((w) => w.normalize('NFD')[0].toUpperCase()).join('')
  return out.length >= 2 && out.length <= 8 ? out : null
}

